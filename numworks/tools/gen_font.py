#!/usr/bin/env python3
"""Generate the bitmap fonts used by the PC test harness (numworks/desktop).

On the calculator, text is drawn by the calculator's own fonts. The PC harness
needs look-alikes of the same size (small: 7x14, large: 10x18 pixels per
character) so screenshots show the real layout. This renders DejaVu Sans Mono
into bit masks and writes `numworks/desktop/src/font_gen.rs`.

    python3 numworks/tools/gen_font.py
"""

import pathlib

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "numworks" / "desktop" / "src" / "font_gen.rs"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"


def render(w, h, size):
    """Returns one list of `h` row masks per ASCII character 32..126."""
    font = ImageFont.truetype(FONT, size)
    glyphs = []
    for code in range(32, 127):
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((w / 2, h / 2), chr(code), font=font, fill=255, anchor="mm")
        rows = []
        for y in range(h):
            m = 0
            for x in range(w):
                if img.getpixel((x, y)) >= 110:
                    m |= 1 << x
            rows.append(m)
        glyphs.append(rows)
    return glyphs


def main():
    out = ["//! GENERATED by `numworks/tools/gen_font.py`. Do not edit by hand.", ""]
    for name, (w, h, size) in {"SMALL": (7, 14, 11), "LARGE": (10, 18, 15)}.items():
        out.append(f"/// {w}x{h} font, ASCII 32..=126, one bit mask per row (bit x = column x).")
        out.append(f"pub static {name}: [[u16; {h}]; 95] = [")
        for rows in render(w, h, size):
            out.append("    [" + ", ".join(f"0x{r:04X}" for r in rows) + "],")
        out.append("];")
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
