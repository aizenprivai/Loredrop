#!/usr/bin/env python3
"""Generate the NumWorks edition's block table and textures from Loredrop's data.

Reads the PC game's `assets/data/blocks.toml` and `assets/textures/block/*.png`
and writes `numworks/core/src/gen_blocks.rs`, a plain Rust file containing:

* one constant per block (`pub const STONE: Block = 1;` ...),
* the block property table (`BLOCKS`), with hardness, tool, drops, layer...
* every texture used, converted to 16x16 RGB565 (`TEXTURES`), with the biome
  tint baked in and fully transparent pixels replaced by the `TRANSPARENT` key.

The generated file is committed, so building the calculator app needs no Python.
Re-run this script whenever the PC game's blocks or textures change:

    python3 numworks/tools/gen_blocks.py

Only cube-shaped blocks are exported: the calculator renderer has no plant
(cross-shaped) blocks yet.
"""

import pathlib
import tomllib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
BLOCKS_TOML = ROOT / "assets" / "data" / "blocks.toml"
TEXTURE_DIR = ROOT / "assets" / "textures" / "block"
OUT = ROOT / "numworks" / "core" / "src" / "gen_blocks.rs"

# Biome tints baked into the textures (the calculator has a single tint per
# block). Values are the PC game's plains colours from biomes.toml.
TINTS = {"grass": (0x91, 0xBD, 0x59), "foliage": (0x77, 0xAB, 0x2F), "water": (0x3F, 0x76, 0xE4)}

# Colour used to mark see-through texels. Must match `TRANSPARENT` in blocks.rs.
TRANSPARENT = 0xF81F

TOOLS = {None: 0, "pickaxe": 1, "axe": 2, "shovel": 3, "hoe": 4}
LAYERS = {"opaque": 0, "cutout": 1, "translucent": 2}


def rgb565(r, g, b):
    """Pack an 8-bit RGB colour into 16-bit RGB565, the calculator's screen format."""
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def face_value(table, face):
    """Resolve a per-face table such as `textures` or `tint` for one face.

    `face` is "top", "bottom" or "side"; more specific keys win, like on PC.
    For sides, the PC game's `north` face (the "front" of crafting tables and
    furnaces) is preferred so the calculator shows the recognisable front.
    """
    if table is None:
        return None
    if isinstance(table, str):
        return table
    if face == "side":
        for key in ("north", "side", "all"):
            if key in table:
                return table[key]
        return None
    return table.get(face, table.get("all"))


def load_texture(name, tint):
    """Load one 16x16 texture as a list of 256 RGB565 values."""
    img = Image.open(TEXTURE_DIR / f"{name}.png").convert("RGBA")
    if img.size != (16, 16):
        img = img.resize((16, 16), Image.NEAREST)
    out = []
    for y in range(16):
        for x in range(16):
            r, g, b, a = img.getpixel((x, y))
            if a < 64:
                out.append(TRANSPARENT)
                continue
            if tint:
                tr, tg, tb = TINTS[tint]
                r, g, b = r * tr // 255, g * tg // 255, b * tb // 255
            c = rgb565(r, g, b)
            # Never let a real pixel collide with the transparency key.
            out.append(c ^ 0x0020 if c == TRANSPARENT else c)
    return out


def first_drop(drops, name, block_names):
    """The block a broken block gives, or None.

    The calculator inventory only holds blocks for now, so item drops (coal,
    sticks...) and chance-based drops are ignored.
    """
    if drops is None:
        return name
    if drops == "none":
        return None
    first = drops.split(",")[0].strip()
    if "@" in first:
        return None
    first = first.split(":")[0]
    return first if first in block_names else None


def main():
    data = tomllib.loads(BLOCKS_TOML.read_text())
    blocks = [b for b in data["block"] if b.get("shape", "cube") == "cube" and b.get("layer") != "invisible"]
    block_names = {b["name"] for b in blocks}

    textures = []  # list of (key, pixels)
    tex_index = {}

    def tex(name, tint):
        key = (name, tint)
        if key not in tex_index:
            tex_index[key] = len(textures)
            textures.append((key, load_texture(name, tint)))
        return tex_index[key]

    rows = []
    for b in blocks:
        faces = []
        for face in ("top", "side", "bottom"):
            tname = face_value(b.get("textures"), face)
            faces.append(tex(tname, face_value(b.get("tint"), face)))
        drop = first_drop(b.get("drops"), b["name"], block_names)
        rows.append((b, faces, drop))

    ids = {b["name"]: i + 1 for i, (b, _, _) in enumerate(rows)}

    lines = [
        "//! GENERATED by `numworks/tools/gen_blocks.py` from the PC game's",
        "//! `assets/data/blocks.toml` and block textures. Do not edit by hand.",
        "",
        "use crate::blocks::{Block, BlockDef, Layer, Tool};",
        "",
        "/// Empty space.",
        "pub const AIR: Block = 0;",
    ]
    for b, _, _ in rows:
        lines.append(f"/// {b.get('display', b['name'])}.")
        lines.append(f"pub const {b['name'].upper()}: Block = {ids[b['name']]};")
    lines.append("")
    lines.append(f"/// Number of block types, air included.")
    lines.append(f"pub const BLOCK_COUNT: usize = {len(rows) + 1};")
    lines.append("")
    lines.append("/// Properties of every block, indexed by block id.")
    lines.append("pub static BLOCKS: [BlockDef; BLOCK_COUNT] = [")
    lines.append(
        '    BlockDef { name: "Air", layer: Layer::Air, solid: false, tex: [0, 0, 0], hardness: 0.0, '
        "tool: Tool::None, needs_tool: false, drop: AIR, light: 0 },"
    )
    for b, faces, drop in rows:
        layer = b.get("layer", "opaque")
        layer_rs = {"opaque": "Opaque", "cutout": "Cutout", "translucent": "Water"}[layer]
        if b["name"] == "lava":
            layer_rs = "Lava"
        solid = b.get("solid", True)
        hardness = float(b.get("hardness", 0.0))
        tool = (b.get("tool") or "none").capitalize()
        needs = "harvest_level" in b
        drop_rs = drop.upper() if drop else "AIR"
        name = b.get("display", b["name"]).replace('"', "'")
        lines.append(
            f'    BlockDef {{ name: "{name}", layer: Layer::{layer_rs}, solid: {str(solid).lower()}, '
            f"tex: [{faces[0]}, {faces[1]}, {faces[2]}], hardness: {hardness!r}, tool: Tool::{tool}, "
            f"needs_tool: {str(needs).lower()}, drop: {drop_rs}, light: {int(b.get('light', 0))} }},"
        )
    lines.append("];")
    lines.append("")
    lines.append("/// Number of textures.")
    lines.append(f"pub const TEXTURE_COUNT: usize = {len(textures)};")
    lines.append("")
    lines.append("/// 16x16 RGB565 textures, row by row. See `blocks::TRANSPARENT`.")
    lines.append("pub static TEXTURES: [[u16; 256]; TEXTURE_COUNT] = [")
    for (name, tint), px in textures:
        lines.append(f"    // {name}{' (' + tint + ' tint)' if tint else ''}")
        lines.append("    [")
        for row in range(16):
            vals = ", ".join(f"0x{v:04X}" for v in px[row * 16:(row + 1) * 16])
            lines.append(f"        {vals},")
        lines.append("    ],")
    lines.append("];")
    lines.append("")
    # Mining cracks: the PC game's destroy_stage_0..9 overlays as bit masks
    # (bit x of row y set = darken that texel).
    lines.append("/// Mining crack overlays (10 stages), one 16-bit mask per texture row.")
    lines.append("pub static CRACKS: [[u16; 16]; 10] = [")
    for stage in range(10):
        img = Image.open(TEXTURE_DIR / f"destroy_stage_{stage}.png").convert("RGBA").resize((16, 16), Image.NEAREST)
        masks = []
        for y in range(16):
            mask = 0
            for x in range(16):
                if img.getpixel((x, y))[3] >= 64:
                    mask |= 1 << x
            masks.append(f"0x{mask:04X}")
        lines.append(f"    [{', '.join(masks)}],")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} blocks, {len(textures)} textures")


if __name__ == "__main__":
    main()
